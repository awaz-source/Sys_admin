#!/usr/bin/env bash
# Summarize sudo activity from Linux authentication logs or the system journal.
# Read-only: this script does not modify sudo policy or execute logged commands.
#
# Examples:
#   sudo ./sudo_activity_report.sh
#   ./sudo_activity_report.sh -i /var/log/auth.log -n 50
#   ./sudo_activity_report.sh -i secure-archive.log.gz -o sudo-report.txt
#   sudo ./sudo_activity_report.sh -s '7 days ago'
#
# Exit codes: 0 report completed, 2 invalid input or collection failure.

set -uo pipefail
umask 077

input=""
output=""
since="24 hours ago"
max_commands=30

usage() {
  cat <<'USAGE'
Usage: sudo_activity_report.sh [-i LOG] [-s SINCE] [-n COUNT] [-o REPORT]

Options:
  -i LOG     Read an auth/secure log or .gz archive instead of live data
  -s SINCE   journalctl time expression for live collection (default: 24 hours ago)
  -n COUNT   Maximum command records shown (default: 30)
  -o REPORT  Save the report with permissions set to 600
  -h         Show this help

Without -i, the script queries journal entries generated by sudo, then falls
back to /var/log/auth.log or /var/log/secure. It summarizes command execution,
authentication failures, policy denials, and PAM sessions. High-risk command
patterns are review leads and are not proof of malicious activity.
USAGE
}

while getopts ":i:s:n:o:h" option; do
  case "$option" in
    i) input=$OPTARG ;;
    s) since=$OPTARG ;;
    n) max_commands=$OPTARG ;;
    o) output=$OPTARG ;;
    h) usage; exit 0 ;;
    :) printf 'Option -%s requires an argument.\n' "$OPTARG" >&2; exit 2 ;;
    \?) printf 'Unknown option: -%s\n' "$OPTARG" >&2; usage >&2; exit 2 ;;
  esac
done

if [[ ! $max_commands =~ ^[1-9][0-9]*$ ]]; then
  printf 'COUNT must be a positive integer.\n' >&2
  exit 2
fi
if [[ -n $input && ! -r $input ]]; then
  printf 'Input log is not readable: %s\n' "$input" >&2
  exit 2
fi

tmp_raw=$(mktemp)
tmp_sudo=$(mktemp)
tmp_commands=$(mktemp)
tmp_findings=$(mktemp)
tmp_report=$(mktemp)
trap 'rm -f "$tmp_raw" "$tmp_sudo" "$tmp_commands" "$tmp_findings" "$tmp_report"' EXIT

source_description=""
if [[ -n $input ]]; then
  source_description=$input
  if [[ $input == *.gz ]]; then
    command -v gzip >/dev/null 2>&1 || {
      printf 'gzip is required to read: %s\n' "$input" >&2
      exit 2
    }
    gzip -cd -- "$input" >"$tmp_raw" || {
      printf 'Unable to decompress input log: %s\n' "$input" >&2
      exit 2
    }
  else
    cp -- "$input" "$tmp_raw" || exit 2
  fi
elif command -v journalctl >/dev/null 2>&1; then
  source_description="journalctl sudo since $since"
  journalctl --no-pager --since "$since" _COMM=sudo >"$tmp_raw" 2>/dev/null || {
    printf 'Unable to query sudo journal entries. Try sudo or provide -i LOG.\n' >&2
    exit 2
  }
else
  for candidate in /var/log/auth.log /var/log/secure; do
    if [[ -r $candidate ]]; then
      source_description=$candidate
      cp -- "$candidate" "$tmp_raw" || exit 2
      break
    fi
  done
  [[ -n $source_description ]] || {
    printf 'No journalctl or readable authentication log was found.\n' >&2
    exit 2
  }
fi

grep -Ei 'sudo(\[[0-9]+\])?:|pam_unix\(sudo:' "$tmp_raw" >"$tmp_sudo" || true

auth_failures=0
policy_denials=0
sessions_opened=0
sessions_closed=0
command_count=0
finding_count=0

add_finding() {
  local severity=$1 actor=$2 reason=$3 command=$4
  printf '%s\t%s\t%s\t%s\n' "$severity" "$actor" "$reason" "$command" >>"$tmp_findings"
  finding_count=$((finding_count + 1))
}

while IFS= read -r line || [[ -n $line ]]; do
  if grep -Eqi 'authentication failure|incorrect password attempt' <<<"$line"; then
    auth_failures=$((auth_failures + 1))
  fi
  denied=false
  if grep -Eqi 'NOT in sudoers|not allowed to execute|command not allowed' <<<"$line"; then
    policy_denials=$((policy_denials + 1))
    denied=true
  fi
  grep -Eqi 'session opened' <<<"$line" && sessions_opened=$((sessions_opened + 1))
  grep -Eqi 'session closed' <<<"$line" && sessions_closed=$((sessions_closed + 1))

  [[ $denied == false && $line == *"COMMAND="* ]] || continue
  command=${line##*COMMAND=}
  prefix=${line%%COMMAND=*}
  actor=unknown
  run_as=unknown

  if [[ $line =~ sudo(\[[0-9]+\])?:[[:space:]]+([^[:space:]:]+)[[:space:]]*: ]]; then
    actor=${BASH_REMATCH[2]}
  fi
  if [[ $prefix =~ USER=([^[:space:];]+) ]]; then
    run_as=${BASH_REMATCH[1]}
  fi

  command_count=$((command_count + 1))
  printf '%s\t%s\t%s\n' "$actor" "$run_as" "$command" >>"$tmp_commands"

  if grep -Eqi '(^|[[:space:]])(/usr)?/bin/(ba|da|z|k|c)?sh([[:space:]]|$)|(^|[[:space:]])(ba|da|z|k|c)?sh([[:space:]]+-c|$)' <<<"$command"; then
    add_finding HIGH "$actor" 'interactive shell or shell command executed through sudo' "$command"
  fi
  if grep -Eqi '(^|[[:space:]])(/tmp|/var/tmp|/dev/shm)/' <<<"$command"; then
    add_finding MEDIUM "$actor" 'privileged command references a temporary path' "$command"
  fi
  if grep -Eqi '(^|[[:space:]/])(useradd|usermod|userdel|groupadd|groupmod|groupdel|passwd)([[:space:]]|$)' <<<"$command"; then
    add_finding MEDIUM "$actor" 'privileged identity-management command' "$command"
  fi
  if grep -Eqi '(^|[[:space:]/])(rm|shred|truncate)([[:space:]].*)?(/var/log|/var/audit|/var/log/audit)' <<<"$command"; then
    add_finding HIGH "$actor" 'command may delete or truncate security logs' "$command"
  fi
done <"$tmp_sudo"

sudo_line_count=$(awk 'END {print NR + 0}' "$tmp_sudo")

{
  printf 'Sudo Activity Report\n'
  printf 'Generated (UTC): %s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
  printf 'Host: %s\n' "$(hostname 2>/dev/null || printf unknown)"
  printf 'Source: %s\n' "$source_description"
  printf 'Matched sudo log lines: %d\n' "$sudo_line_count"
  printf 'Privileged commands: %d\n' "$command_count"
  printf 'Authentication failures: %d\n' "$auth_failures"
  printf 'Policy denials: %d\n' "$policy_denials"
  printf 'Sessions opened: %d\n' "$sessions_opened"
  printf 'Sessions closed: %d\n' "$sessions_closed"
  printf 'Review findings: %d\n' "$finding_count"

  printf '\n== Commands by invoking user ==\n'
  if (( command_count == 0 )); then
    printf 'No sudo command records matched.\n'
  else
    cut -f1 "$tmp_commands" | sort | uniq -c | sort -nr | awk '{print $1 " | " $2}'
  fi

  printf '\n== Commands by target user ==\n'
  if (( command_count == 0 )); then
    printf 'No sudo command records matched.\n'
  else
    cut -f2 "$tmp_commands" | sort | uniq -c | sort -nr | awk '{print $1 " | " $2}'
  fi

  printf '\n== Privileged commands (maximum %d) ==\n' "$max_commands"
  if (( command_count == 0 )); then
    printf 'None.\n'
  else
    head -n "$max_commands" "$tmp_commands" \
      | awk -F'\t' '{print "actor=" $1 " | target=" $2 " | command=" $3}'
    if (( command_count > max_commands )); then
      printf '[Additional commands omitted: %d]\n' "$((command_count - max_commands))"
    fi
  fi

  printf '\n== Findings requiring review ==\n'
  if (( finding_count == 0 )); then
    printf 'No configured risk patterns were identified.\n'
  else
    sort -t $'\t' -k1,1 -k2,2 "$tmp_findings" \
      | awk -F'\t' '{print $1 " | actor=" $2 " | " $3 " | command=" $4}'
  fi

  printf '\n== Analyst guidance ==\n'
  printf 'Compare activity with tickets, maintenance windows, and approved administrator roles.\n'
  printf 'Correlate unexplained commands with authentication, process, audit, and file telemetry.\n'
} >"$tmp_report"

if [[ -n $output ]]; then
  cp -- "$tmp_report" "$output" || {
    printf 'Unable to write report: %s\n' "$output" >&2
    exit 2
  }
  chmod 600 "$output"
  printf 'Report written to %s\n' "$output"
else
  cat "$tmp_report"
fi

exit 0
